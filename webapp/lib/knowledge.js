  // 归一化：小写 + 去空白，便于命中判断
  function _norm(s) {
    return String(s || '').toLowerCase();
  }

  /**
   * 检索：返回用户这句话命中的知识条目（去重、保序）。
   * 命中规则：条目任一 trigger 作为子串出现在用户文本里。
   * @param {string} text 用户发言
   * @param {number} [max=3] 最多返回几条（避免注入过长）
   */
  function retrieve(text, max) {
    const q = _norm(text);
    if (!q) return [];
    const limit = max || 3;
    const hits = [];
    for (const e of ENTRIES) {
      if (e.triggers.some(t => q.indexOf(_norm(t)) !== -1)) {
        hits.push(e);
        if (hits.length >= limit) break;
      }
    }
    return hits;
  }

  /**
   * 构造注入文本：把命中的条目打包成一段「可调用背景知识」，
   * 附带使用说明，强制小知用大白话讲、别堆术语别念出处。
   * 没命中返回 ''（调用方据此决定是否注入）。
   * @param {string} text 用户发言
   * @returns {string}
   */
  function buildInjection(text) {
    const hits = retrieve(text);
    if (!hits.length) return '';

    const body = hits.map(e => {
      let s = `· 【${e.title}】${e.oneLine}\n  展开：${e.plain}`;
      if (e.source) s += `\n  （如果 TA 想深究才说的严谨依据：${e.source}）`;
      return s;
    }).join('\n\n');

    return `【可调用的背景知识 — 仅供你参考】\n` +
      `TA 这句话可能想了解下面的概念。只在 TA 真的问起、或自然相关时用；` +
      `务必用你自己的话、像朋友聊天一样讲清楚，别照念、别堆术语、别报出处（除非 TA 想深究）。` +
      `先接住情绪，再顺势解释，一次讲一个点就好。\n\n${body}`;
  }

